create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default 'Adventurer',
  email text,
  avatar text default '🧙',
  xp integer not null default 0,
  gold integer not null default 100,
  intellect integer not null default 10,
  strength integer not null default 10,
  vitality integer not null default 10,
  creativity integer not null default 10,
  streak integer not null default 0,
  last_active_date date,
  created_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(trim(title)) between 1 and 150),
  category text not null check (category in ('Coding','Study','Health','Personal Growth','Social')),
  description text default '',
  reward_xp integer not null default 50 check (reward_xp between 10 and 500),
  reward_gold integer not null default 10,
  attribute_gain integer not null default 1,
  status text not null default 'pending' check (status in ('pending','completed')),
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.shop_items (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null,
  price integer not null check (price >= 0),
  type text not null check (type in ('item','theme','badge')),
  icon text not null
);

create table if not exists public.inventory (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  item_id bigint not null references public.shop_items(id) on delete cascade,
  purchased_at timestamptz not null default now(),
  unique(user_id, item_id)
);

