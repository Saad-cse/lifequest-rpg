-- Server-side quest completion. The function checks ownership and updates
-- XP, gold, attributes, streak and task status atomically.
create or replace function public.complete_quest(p_task_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  t public.tasks;
  u public.profiles;
  attr text;
  before_level integer;
  after_level integer;
  new_streak integer;
  today date := current_date;
  prev date;
  reward jsonb;
  user_json jsonb;
begin
  select * into t from public.tasks
  where id = p_task_id and user_id = auth.uid()
  for update;

  if not found then
    raise exception 'Quest not found';
  end if;

  if t.status = 'completed' then
    raise exception 'Quest is already completed';
  end if;

  select * into u from public.profiles
  where id = auth.uid()
  for update;

  before_level := floor(sqrt(greatest(u.xp,0)::numeric / 100)) + 1;
  after_level := floor(sqrt(greatest(u.xp + t.reward_xp,0)::numeric / 100)) + 1;

  attr := case t.category
    when 'Coding' then 'intellect'
    when 'Study' then 'intellect'
    when 'Health' then 'strength'
    when 'Personal Growth' then 'creativity'
    when 'Social' then 'vitality'
  end;

  new_streak := u.streak;
  if u.last_active_date is distinct from today then
    if u.last_active_date = today - 1 then
      new_streak := u.streak + 1;
    else
      new_streak := 1;
    end if;
  end if;

  update public.profiles
  set
    xp = u.xp + t.reward_xp,
    gold = u.gold + t.reward_gold,
    intellect = intellect + case when attr='intellect' then t.attribute_gain else 0 end,
    strength = strength + case when attr='strength' then t.attribute_gain else 0 end,
    vitality = vitality + case when attr='vitality' then t.attribute_gain else 0 end,
    creativity = creativity + case when attr='creativity' then t.attribute_gain else 0 end,
    streak = new_streak,
    last_active_date = today
  where id = auth.uid();

  update public.tasks
  set status='completed', completed_at=now()
  where id=t.id;

  select to_jsonb(p) into user_json from public.profiles p where p.id=auth.uid();

  reward := jsonb_build_object(
    'xp', t.reward_xp,
    'gold', t.reward_gold,
    'attribute', attr,
    'attributeGain', t.attribute_gain,
    'levelUp', after_level > before_level,
    'newLevel', after_level
  );

  return jsonb_build_object('user', user_json, 'reward', reward);
end;
$$;

grant execute on function public.complete_quest(bigint) to authenticated;

-- Atomic shop purchase.
create or replace function public.buy_shop_item(p_item_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  item public.shop_items;
  current_gold integer;
begin
  select * into item from public.shop_items where id=p_item_id;
  if not found then raise exception 'Item not found'; end if;

  if exists(select 1 from public.inventory where user_id=auth.uid() and item_id=item.id) then
    raise exception 'You already own this item';
  end if;

  select gold into current_gold from public.profiles where id=auth.uid() for update;
  if current_gold < item.price then raise exception 'Not enough gold'; end if;

  update public.profiles set gold=gold-item.price where id=auth.uid();
  insert into public.inventory(user_id,item_id) values(auth.uid(),item.id);

  return jsonb_build_object('message', item.name || ' purchased');
end;
$$;

grant execute on function public.buy_shop_item(bigint) to authenticated;

